def _register_communicator(module: str, class_name: str, root: Path) -> None:
    extra_path = root / "backend" / "lab_communicator" / "extra_communicators.py"
    block = (
        f"\nfrom lab_communicator.{module} import {class_name}\n"
        f"from lab_communicator.shared.communicator_factory import register_communicator\n"
        f'register_communicator("{module}", {class_name})\n'
    )
    existing = extra_path.read_text(encoding="utf-8") if extra_path.is_file() else ""
    if f'register_communicator("{module}"' in existing:
        return
    with open(extra_path, "a", encoding="utf-8") as f:
        if existing and not existing.endswith("\n"):
            f.write("\n")
        f.write(block)


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a lab_communicator backend scaffold.")
    parser.add_argument(
        "name",
        help="Python package name (snake_case), e.g. bench_sim -> BenchSimLabCommunicator",
    )
    parser.add_argument(
        "--with-lab-view",
        action="store_true",
        help="Copy lab_view starter files from real/lab_view/default into --lab-view-root.",
    )
    parser.add_argument(
        "--lab-view-root",
        type=str,
        default="",
        help="Destination directory for the bundle (default: backend/lab_communicator/<name>/lab_view).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Allow overwriting an existing communicator package directory.",
    )
    parser.add_argument(
        "--no-register",
        action="store_true",
        help="Do not append register_communicator() to lab_communicator/extra_communicators.py.",
    )
    args = parser.parse_args()

    name = args.name.strip().lower().replace("-", "_")
    if not _NAME_RE.match(name):
        print("Invalid name: use snake_case [a-z][a-z0-9_]*", file=sys.stderr)
        return 2
    if name in _RESERVED:
        print(f"Reserved package name: {name}", file=sys.stderr)
        return 2

    root = _repo_root()
    lc_root = root / "backend" / "lab_communicator"
    pkg = lc_root / name
    if pkg.exists() and not args.force:
        print(f"Already exists (use --force): {pkg}", file=sys.stderr)
        return 2

    class_name = _snake_to_class(name) + "LabCommunicator"

    if pkg.exists():
        shutil.rmtree(pkg)
    pkg.mkdir(parents=True)

    _write_init(pkg, name, class_name)
    _write_communicator(pkg, name, class_name)
    _write_primitives(pkg, name, class_name)

    lv_template = lc_root / "real" / "lab_view" / "default"
    if not lv_template.is_dir():
        print(f"Missing template lab_view: {lv_template}", file=sys.stderr)
        return 2

    lab_view_dest: Path | None = None
    lab_view_rel = ""
    if args.with_lab_view:
        lab_view_dest = Path(args.lab_view_root) if args.lab_view_root else pkg / "lab_view"
        if not lab_view_dest.is_absolute():
            lab_view_dest = root / lab_view_dest
        _copy_lab_view(lv_template, lab_view_dest, communicator_id=name)
        lab_view_rel = lab_view_dest.relative_to(root).as_posix()

    _write_integrators_md(pkg, name, class_name, lab_view_rel=lab_view_rel or f"backend/lab_communicator/{name}/lab_view")

    if not args.no_register:
        _register_communicator(name, class_name, root)

    print(f"Created package: backend/lab_communicator/{name}/")
    print(f"  Class: {class_name}")
    print(f"  Guide: backend/lab_communicator/{name}/INTEGRATORS.md")
    if lab_view_dest is not None:
        print(f"  lab_view: {lab_view_dest.relative_to(root)}")
        print()
        print("Next steps:")
        print(f"  1. .env -> LAB_VIEW_PATH={lab_view_rel}")
        print(f'  2. lab_manifest.json -> "communicator": "{name}"')
        print(f"  3. Edit active_catalog.json + component_library.json for your bench")
        print(f"  4. Implement lab_communicator/{name}/primitives.py")
    else:
        print()
