#!/usr/bin/env python3
"""Scaffold a new lab_communicator backend + optional lab_view bundle for cloud-labs.

Use this when building a **digital twin**, bench simulator, or any lab that should
speak the same HTTP + JSON protocol as cloud-labs (without forking ``main.py``).

Quick start (from repository root)::

  python scripts/create_lab_communicator.py bench_twin --with-lab-view
  # .env → LAB_VIEW_PATH=backend/lab_communicator/bench_twin/lab_view
  # Edit lab_view/active_catalog.json + component_library.json for your parts
  # Implement backend/lab_communicator/bench_twin/primitives.py

What cloud-labs needs from you (see generated INTEGRATORS.md for the full checklist):

  1. **lab_view bundle** — mandatory JSON files (layout, catalog, manifest, …)
  2. **lab_manifest.json** — ``"communicator": "<your_id>"`` selects your class
  3. **Register backend** — script appends to ``lab_communicator/extra_communicators.py``
  4. **LabCommunicator subclass** — ``communicator.py`` hooks + ``primitives.py`` hardware
  5. **Catalog** — ``component_library.json`` declares capabilities per ``tag_id``

Architecture references:

  - ``backend/lab_communicator/README.md`` — adapter layout + bootstrap rules
  - ``backend/lab_model/ARCHITECTURE.md`` — primitives, tunables, telemetry
  - ``capability_contract.md`` / ``CLOUDLAB_CONTRACT.md`` — catalog ↔ hardware contract

Rules:

  - Package name must be ``snake_case`` (letters, digits, underscore; cannot start with a digit).
  - Names ``mock``, ``real``, ``shared``, ``tests`` are reserved.
"""

