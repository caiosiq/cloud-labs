def _copy_lab_view(template: Path, dest: Path, *, communicator_id: str) -> None:
    if dest.exists():
        raise SystemExit(f"lab_view destination already exists: {dest}")
    shutil.copytree(template, dest)
    lab_state_path = dest / "lab_state.json"
    if not lab_state_path.is_file():
        with open(lab_state_path, "w", encoding="utf-8") as f:
            json.dump(_minimal_lab_state(), f, indent=2)
            f.write("\n")
    manifest_path = dest / "lab_manifest.json"
    manifest: dict = {
        "version": 1,
        "description": "Deployment identity for this lab view bundle.",
        "communicator": communicator_id,
        "session_checkpoint": True,
    }
    if communicator_id == "real":
        manifest["lab_automation_path"] = "../lab_automation"
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a lab_communicator backend scaffold.")
    parser.add_argument(
        "name",
        help="Python package name (snake_case), e.g. bench_sim → BenchSimLabCommunicator",
    )
    parser.add_argument(
        "--with-lab-view",
        action="store_true",
        help="Copy lab_view starter files from real/lab_view/default into --lab-view-root.",
    )
    parser.add_argument(
        "--lab-view-root",
        type=str,
        default="",
        help="Destination directory for the bundle (default: backend/lab_communicator/<name>/lab_view).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Allow overwriting an existing communicator package directory.",
    )
    args = parser.parse_args()

    name = args.name.strip().lower().replace("-", "_")
    if not _NAME_RE.match(name):
        print("Invalid name: use snake_case [a-z][a-z0-9_]*", file=sys.stderr)
        return 2
    if name in _RESERVED:
        print(f"Reserved package name: {name}", file=sys.stderr)
        return 2

    root = _repo_root()
    lc_root = root / "backend" / "lab_communicator"
    pkg = lc_root / name
    if pkg.exists() and not args.force:
        print(f"Already exists (use --force): {pkg}", file=sys.stderr)
        return 2

    class_name = _snake_to_class(name) + "LabCommunicator"

    if pkg.exists():
        shutil.rmtree(pkg)
    pkg.mkdir(parents=True)

    _write_init(pkg, name, class_name)
    _write_communicator(pkg, name, class_name)
    _write_primitives(pkg, name, class_name)

    lv_template = lc_root / "real" / "lab_view" / "default"
    if not lv_template.is_dir():
        print(f"Missing template lab_view: {lv_template}", file=sys.stderr)
        return 2

    lab_view_dest: Path | None = None
    if args.with_lab_view:
        lab_view_dest = Path(args.lab_view_root) if args.lab_view_root else pkg / "lab_view"
        if not lab_view_dest.is_absolute():
            lab_view_dest = root / lab_view_dest
        _copy_lab_view(lv_template, lab_view_dest, communicator_id=name)

    print(f"Created package: backend/lab_communicator/{name}/")
    print(f"  Class: {class_name}")
    if lab_view_dest is not None:
        print(f"  lab_view: {lab_view_dest.relative_to(root)}")
        print()
        print("Next: set in .env (repo root):")
        print(f"  LAB_VIEW_PATH={lab_view_dest.relative_to(root).as_posix()}")
        print(f"  (lab_manifest.json in that bundle sets communicator={name!r})")
    else:
        print()
        print("No lab_view copied. Point LAB_VIEW_PATH at any bundle that contains:")
        print("  lab_manifest.json, layout.json, laser_lines.json, component_library.json,")
        print("  active_catalog.json, motor_rotations.json (+ lab_state.json recommended).")
    print()
    print(
        "Register your class in lab_communicator/shared/communicator_factory.py "
        f"(add {name!r} to create_communicator)."
    )
    print("CI guardrails: lab_model.platform.validate_platform_integrity()")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
