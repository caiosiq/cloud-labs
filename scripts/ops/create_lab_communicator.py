#!/usr/bin/env python3
"""Scaffold a new lab_communicator backend package + optional lab_view bundle.

Usage (from repository root):

  python scripts/ops/create_lab_communicator.py my_backend
  python scripts/ops/create_lab_communicator.py my_backend --with-lab-view
  python scripts/ops/create_lab_communicator.py my_backend --with-lab-view --lab-view-root backend/lab_communicator/my_backend/lab_view

See backend/lab_communicator/README.md for architecture and wiring into main.py.

Rules:
  - Package name must be ``snake_case`` (letters, digits, underscore; cannot start with a digit).
  - Names ``mock``, ``real``, ``shared``, ``tests`` are reserved.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from datetime import datetime
from pathlib import Path


_RESERVED = frozenset({"mock", "real", "shared", "tests"})
_NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _snake_to_class(name: str) -> str:
    parts = [p for p in name.split("_") if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def _minimal_lab_state() -> dict:
    return {
        "system_status": "IDLE",
        "last_updated": datetime.now().isoformat(),
        "components": {},
        "optimization_step": 0,
        "optimization_run_dir": None,
        "holding": {
            "tag_id": None,
            "nominal_pose": None,
            "requires_operator_confirm": False,
        },
    }


